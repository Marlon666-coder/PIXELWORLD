#!/usr/bin/env node
/**
 * Guards against drift between the committed Database types and the types the
 * Supabase CLI generates from the actual migrated schema.
 *
 *   node scripts/compare-db-types.mjs <committed.ts> <generated.ts>
 *
 * Comparison is structural: comments and insignificant whitespace are stripped,
 * and only the shape of the two files is compared. If they differ, it prints a
 * hint and exits non-zero so CI fails. Regenerate with:
 *   supabase gen types typescript --local > lib/supabase/database.types.ts
 */
import { readFileSync } from "node:fs";

function normalize(source) {
  return source
    .replace(/\/\*[\s\S]*?\*\//g, "") // block comments
    .replace(/\/\/.*$/gm, "") // line comments
    .replace(/\s+/g, " ") // collapse whitespace
    .replace(/,\s*}/g, " }") // tolerate trailing commas
    .replace(/,\s*]/g, " ]")
    .replace(/([=:|&(])\s*\|/g, "$1") // leading union bar is semantically insignificant
    .replace(/\s*\|\s*/g, "|") // normalise spacing around union bars
    .replace(/\s*([{};,:])\s*/g, "$1") // normalise spacing around punctuation
    .replace(/;}/g, "}")
    .trim();
}

const [, , committedPath, generatedPath] = process.argv;
if (!committedPath || !generatedPath) {
  console.error("usage: compare-db-types.mjs <committed.ts> <generated.ts>");
  process.exit(2);
}

const committed = normalize(readFileSync(committedPath, "utf8"));
const generated = normalize(readFileSync(generatedPath, "utf8"));

if (committed === generated) {
  console.log("✓ Database types match the migrated schema.");
  process.exit(0);
}

// Show the first point of divergence to make failures actionable.
let i = 0;
while (i < committed.length && i < generated.length && committed[i] === generated[i]) i += 1;
const context = 90;
console.error("✗ Committed Database types differ from the schema generated by the Supabase CLI.");
console.error("  Regenerate with: supabase gen types typescript --local > lib/supabase/database.types.ts\n");
console.error("  committed:  …" + committed.slice(Math.max(0, i - context), i + context));
console.error("  generated:  …" + generated.slice(Math.max(0, i - context), i + context));
process.exit(1);
